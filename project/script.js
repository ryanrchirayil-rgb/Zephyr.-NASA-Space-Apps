// OPEN ARTIFACT STORY

const storyButtons = document.querySelectorAll(".story-button");

const modal = document.getElementById("story-modal");

const closeModal = document.getElementById("close-modal");


storyButtons.forEach(function(button) {

    button.addEventListener("click", function() {

        const artifactName = button.dataset.artifact;

        const artifact = artifacts[artifactName];

        document.getElementById("story-location").textContent =
            artifact.location;

        document.getElementById("story-title").textContent =
            artifact.title;

        document.getElementById("story-description").textContent =
            artifact.description;

        document.getElementById("story-extra").textContent =
            artifact.extra;

        modal.classList.add("active");

    });

});


// CLOSE MODAL

closeModal.addEventListener("click", function() {

    modal.classList.remove("active");

});


// CLOSE MODAL WHEN CLICKING OUTSIDE

modal.addEventListener("click", function(event) {

    if (event.target === modal) {
        modal.classList.remove("active");
    }

});


