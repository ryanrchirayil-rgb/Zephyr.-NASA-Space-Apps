let currentQuestion = 0;
let score = 0;
let answered = false;

const questionText = document.getElementById("quiz-question");
const questionNumber = document.getElementById("question-number");
const options = document.querySelector(".quiz-options");
const result = document.getElementById("quiz-result");
const nextButton = document.getElementById("next-question");
const scoreText = document.getElementById("quiz-score");

function loadQuestion() {

    answered = false;

    questionNumber.textContent =
        `Question ${currentQuestion + 1} of 5`;

    questionText.textContent =
        questions[currentQuestion].question;

    options.innerHTML = "";

    result.textContent = "";

    nextButton.style.display = "none";

    questions[currentQuestion].options.forEach((option, index) => {

        const button = document.createElement("button");

        button.className = "quiz-option";
        button.textContent = option;

        
button.addEventListener("click", function () {

    if (answered) return;

    answered = true;

    const correctIndex = questions[currentQuestion].answer;

    const correctAnswer =
        questions[currentQuestion].options[correctIndex];

    // Highlight the correct answer in green
    const allOptions = options.querySelectorAll(".quiz-option");

    allOptions[correctIndex].classList.add("correct");

    if (index === correctIndex) {

        result.textContent = "Correct! Well done.";

        result.style.color = "#64d69a";

        button.classList.add("correct");

        score++;

    }
    else {

        result.textContent =
            `Incorrect! The correct answer is ${correctAnswer}.`;

        result.style.color = "#f08b8b";

        // Highlight the selected wrong answer in red
        button.classList.add("wrong");

    }

    nextButton.style.display = "block";

});


        options.appendChild(button);

    });

}

nextButton.addEventListener("click", function () {

    currentQuestion++;

    if (currentQuestion < questions.length) {
        loadQuestion();
    }
    else {

        questionNumber.textContent = "Quiz Completed!";

        questionText.textContent =
            "You have completed all five questions.";

        options.innerHTML = "";

        result.textContent = "";

        nextButton.style.display = "none";

        scoreText.textContent =
            `Your final score is ${score} / 5`;

    }

});

loadQuestion();


